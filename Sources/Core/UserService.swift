import Foundation
#if os(Linux)
import Glibc
#else
import Darwin
#endif

/// The same per-user service lifecycle for the dashboard server and host daemon.
public struct UserService: Sendable {
    public enum Kind: String, Sendable { case server, daemon }
    public let kind: Kind
    public let executable: URL
    public let arguments: [String]
    public let environment: [String: String]
    public let home: URL
    public init(kind: Kind, executable: URL, arguments: [String] = [], environment: [String: String], home: URL) {
        self.kind = kind; self.executable = executable; self.arguments = arguments; self.environment = environment; self.home = home
    }
    public var label: String { "dev.aelab." + kind.rawValue }
    public var unit: String { "aelab-" + kind.rawValue + ".service" }
    private var marker: String { "aelab-managed-service-v1:" + kind.rawValue }
    public func file(macos: Bool, userHome: URL = FileManager.default.homeDirectoryForCurrentUser, environment: [String: String] = ProcessInfo.processInfo.environment) -> URL {
        if macos { return userHome.appendingPathComponent("Library/LaunchAgents/" + label + ".plist") }
        let config = environment["XDG_CONFIG_HOME"].flatMap { $0.hasPrefix("/") ? URL(fileURLWithPath: $0) : nil } ?? userHome.appendingPathComponent(".config")
        return config.appendingPathComponent("systemd/user/" + unit)
    }
    public func definition(macos: Bool) throws -> Data {
        let values = [executable.path, home.path] + arguments + environment.flatMap { [$0.key, $0.value] }
        guard values.allSatisfy({ $0.rangeOfCharacter(from: .controlCharacters) == nil }), executable.path.hasPrefix("/"),
              environment.keys.allSatisfy({ $0.range(of: "^[A-Za-z_][A-Za-z0-9_]*$", options: .regularExpression) != nil }) else { throw AEError("Service paths and settings must be absolute and contain no control characters") }
        if macos {
            let data = try PropertyListSerialization.data(fromPropertyList: [
                "Label": label,
                "ProgramArguments": [executable.path] + arguments,
                "EnvironmentVariables": environment, "WorkingDirectory": home.path,
                "RunAtLoad": true, "KeepAlive": true, "ThrottleInterval": 3, "Umask": 63,
                "StandardOutPath": home.appendingPathComponent("logs/" + kind.rawValue + ".stdout.log").path,
                "StandardErrorPath": home.appendingPathComponent("logs/" + kind.rawValue + ".stderr.log").path
            ], format: .xml, options: 0)
            return Data(String(decoding: data, as: UTF8.self).replacingOccurrences(of: "<plist", with: "<!-- " + marker + " -->\n<plist").utf8)
        }
        func quoted(_ value: String, command: Bool = false) -> String {
            var escaped = value.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"").replacingOccurrences(of: "%", with: "%%")
            if command { escaped = escaped.replacingOccurrences(of: "$", with: "$$") }
            return "\"" + escaped + "\""
        }
        let command = ([executable.path] + arguments).map { quoted($0, command: true) }.joined(separator: " ")
        let settings = environment.sorted { $0.key < $1.key }.map { "Environment=" + quoted($0.key + "=" + $0.value) }
        return Data((["# " + marker, "[Unit]", "Description=aelab " + kind.rawValue, "[Service]", "Type=exec", "WorkingDirectory=" + quoted(home.path), "ExecStart=" + command] + settings + ["Restart=on-failure", "RestartSec=3", "UMask=0077", "[Install]", "WantedBy=default.target", ""]).joined(separator: "\n").utf8)
    }
    /// Refuse symlinks and foreign definitions; only replace files generated by this API.
    @discardableResult public func write(macos: Bool, userHome: URL = FileManager.default.homeDirectoryForCurrentUser, environment: [String: String] = ProcessInfo.processInfo.environment) throws -> URL {
        let fm = FileManager.default, path = file(macos: macos, userHome: userHome, environment: environment)
        let data = try definition(macos: macos)
        var replacing = false
        if let attrs = try? fm.attributesOfItem(atPath: path.path) {
            guard attrs[.type] as? FileAttributeType == .typeRegular,
                  (attrs[.ownerAccountID] as? NSNumber)?.uint32Value == getuid() else { throw AEError("Refusing to replace an unrelated user service: " + path.path) }
            let existing = try Data(contentsOf: path)
            let owned: Bool
            if macos {
                owned = String(decoding: existing, as: UTF8.self).contains("<!-- " + marker + " -->") && (try? PropertyListSerialization.propertyList(from: existing, format: nil) as? [String: Any])?["Label"] as? String == label
            }
            else { owned = String(decoding: existing, as: UTF8.self).hasPrefix("# " + marker + "\n") }
            guard owned else { throw AEError("Refusing to replace an unrelated user service: " + path.path + "; move the existing definition aside before using --service") }
            replacing = true
        } else if (try? fm.destinationOfSymbolicLink(atPath: path.path)) != nil { throw AEError("Refusing to replace a service symlink: " + path.path) }
        try fm.createDirectory(at: path.deletingLastPathComponent(), withIntermediateDirectories: true)
        try fm.createDirectory(at: home.appendingPathComponent("logs"), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try atomicPrivateWrite(data, to: path, overwrite: replacing)
        return path
    }
    public static var isMacOS: Bool {
        #if os(macOS)
        true
        #else
        false
        #endif
    }
    public func start(macos: Bool = UserService.isMacOS, userHome: URL = FileManager.default.homeDirectoryForCurrentUser, managerEnvironment: [String: String] = ProcessInfo.processInfo.environment,
                      run: @Sendable (String, [String]) async throws -> CommandResult = { tool, args in
                          try await ProcessRunner.run(executable: "/usr/bin/env", arguments: [tool] + args, timeout: 30)
                      }) async throws {
        let path = try write(macos: macos, userHome: userHome, environment: managerEnvironment)
        func command(_ tool: String, _ args: [String], allowFailure: Bool = false) async throws -> CommandResult {
            let result = try await run(tool, args)
            guard allowFailure || result.status == 0 else { throw AEError("Service definition saved at \(path.path), but \(tool) \(args.joined(separator: " ")) failed: \(result.error)\(result.output)") }
            return result
        }
        if macos {
            let domain = "gui/\(getuid())", target = domain + "/" + label
            let loaded = try await command("launchctl", ["print", target], allowFailure: true)
            if loaded.status == 0 { _ = try await command("launchctl", ["bootout", target]) }
            _ = try await command("launchctl", ["enable", target])
            _ = try await command("launchctl", ["bootstrap", domain, path.path])
        } else {
            _ = try await command("systemctl", ["--user", "daemon-reload"])
            _ = try await command("systemctl", ["--user", "enable", unit])
            _ = try await command("systemctl", ["--user", "restart", unit])
        }
        print("Started user service: \(macos ? label : unit)\nDefinition: \(path.path)")
    }
}
