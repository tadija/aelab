import { chromium } from '../Frontend/node_modules/playwright/index.mjs';
import { expect } from '../Frontend/node_modules/@playwright/test/index.mjs';
const origin = process.env.AELAB_TEST_ORIGIN, base = '/lab/aelab';
const browser = await chromium.launch({ headless: true, ...(process.env.AELAB_TEST_BROWSER ? { executablePath: process.env.AELAB_TEST_BROWSER } : {}) });
try {
  const context = await browser.newContext();
  const page = await context.newPage(), errors = [], sent = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('websocket', socket => socket.on('framesent', event => { try { sent.push(JSON.parse(String(event.payload))); } catch {} }));
  await page.goto(origin + base + '/hosts/local/projects/work/');
  await page.getByLabel('Administrator password').fill(process.env.AELAB_TEST_PASSWORD);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.terminal-status')).toHaveAttribute('data-status', 'connected');
  await page.evaluate(() => localStorage.setItem('aelab-tint:local', '#bc78ef'));
  await page.reload();
  await expect(page.locator('.terminal-status')).toHaveAttribute('data-status', 'connected');
  await expect(page.locator('.terminal-logo')).toHaveCSS('color', 'rgb(188, 120, 239)');
  const input = page.locator('.xterm-helper-textarea');
  // A real PTY producer reads the detection response in raw mode, then accepts test commands.
  const fixture = new URL('./program-status-fixture.py', import.meta.url).pathname;
  const command = `python3 '${decodeURIComponent(fixture).replaceAll("'", "'\\''")}'`;
  await input.focus(); await input.pressSequentially(command); await input.press('Enter');
  await expect(page.locator('.xterm-rows')).toContainText('QUERY_OK');
  const replyCount = () => sent.filter(frame => frame.type === 'input' && frame.data?.startsWith('\x1b]7501;?')).length;
  expect(replyCount()).toBe(1);
  const send = async command => { await input.focus(); await input.pressSequentially(command); await input.press('Enter'); };
  await expect(page.locator('.program-status')).toHaveCount(0);
  await send('working'); await expect(page).toHaveTitle('[working 40%] shell@Work');
  await send('blocked'); await expect(page).toHaveTitle('[approval needed] shell@Work');
  await expect(page.locator('.terminal-status')).toHaveAttribute('data-status', 'connected');
  await expect(page.locator('.terminal-logo circle')).toHaveCount(2);
  await expect(page.locator('.terminal-logo')).toHaveCSS('filter', 'none');
  await expect(page.locator('.terminal-logo')).toHaveCSS('width', '24px');
  await expect(page.locator('.terminal-logo')).toHaveCSS('height', '24px');
  await expect(page.locator('.terminal-color')).toHaveCount(0);
  const picker = page.locator('.terminal-cwd input[type=color]');
  await picker.fill('#345678'); await picker.dispatchEvent('input');
  await expect(page.locator('.terminal-logo')).toHaveCSS('color', 'rgb(188, 120, 239)');
  await page.getByRole('button', { name: 'Reset terminal background', exact: true }).click();
  await expect(page.locator('.terminal-logo')).toHaveCSS('color', 'rgb(188, 120, 239)');
  await page.screenshot({ path: '/tmp/aelab-program-status.png' });
  await send('bad'); await expect(page).toHaveTitle('[approval needed] shell@Work');
  await page.getByRole('button', { name: 'Pin terminal session', exact: true }).click();
  await expect(page).toHaveURL(/\/tty\/pinned\//);
  const dashboard = await context.newPage(); await dashboard.goto(origin + base + '/hosts/local/');
  const badge = dashboard.locator('.pin-program-status');
  await expect(badge).toHaveText('approval needed'); await expect(badge).toHaveAttribute('title', /Approve\?/);
  const pinNumber = await dashboard.locator('.pinned-row .pin-number').boundingBox(), pinTitle = await dashboard.locator('.pinned-row .row-title').boundingBox(), statusBox = await badge.boundingBox();
  expect(pinNumber.x + pinNumber.width).toBeLessThanOrEqual(pinTitle.x); expect(pinTitle.x + pinTitle.width).toBeLessThanOrEqual(statusBox.x);
  await page.reload(); await expect(page).toHaveTitle('[approval needed] shell@Work');
  expect(replyCount()).toBe(1);
  await send('clear-child'); await expect(page).toHaveTitle('[working 40%] shell@Work');
  await expect(badge).toHaveText('working 40%');
  await send('soft-reset'); await expect(page).toHaveTitle('[working 40%] shell@Work');
  await send('alternate'); await expect(page).toHaveTitle('[working 40%] shell@Work');
  await send('prompt'); await expect(page).toHaveTitle('shell@Work'); await expect(badge).toHaveCount(0);
  await send('done'); await expect(page).toHaveTitle('[done] shell@Work'); await expect(badge).toHaveText('done');
  await input.focus(); await input.press('ArrowLeft'); await input.press('Enter'); await expect(page).toHaveTitle('shell@Work'); await expect(badge).toHaveCount(0);
  await send('working'); await expect(page).toHaveTitle('[working 40%] shell@Work');
  await send('reset'); await expect(page).toHaveTitle('shell@Work'); await expect(badge).toHaveCount(0);
  await send('working'); await expect(page).toHaveTitle('[working 40%] shell@Work');
  await send('quit'); await input.pressSequentially('exit'); await input.press('Enter');
  await expect(page.locator('.terminal-status')).toHaveAttribute('data-status', 'disconnected');
  await expect(page).toHaveTitle('shell@Work');
  await expect(page.locator('.program-status')).toHaveCount(0);
  const background = await context.newPage(); await background.goto(origin + base + '/hosts/local/projects/work/');
  await expect(background.locator('.terminal-status')).toHaveAttribute('data-status', 'connected');
  const backgroundInput = background.locator('.xterm-helper-textarea');
  await backgroundInput.focus(); await backgroundInput.pressSequentially(command); await backgroundInput.press('Enter');
  await expect(background.locator('.xterm-rows')).toContainText('QUERY_OK');
  await background.getByRole('button', { name: 'Pin terminal session', exact: true }).click();
  await expect(background).toHaveURL(/\/tty\/pinned\//);
  const retainedURL = background.url();
  await backgroundInput.focus(); await backgroundInput.pressSequentially('background'); await backgroundInput.press('Enter');
  await expect(background).toHaveTitle('[working] shell@Work');
  await background.close(); await dashboard.bringToFront();
  await expect(badge).toHaveText('answer needed', { timeout: 4000 });
  await expect(badge).toHaveAttribute('title', /Answer\?/);
  const retained = await context.newPage(); await retained.goto(retainedURL);
  await expect(retained).toHaveTitle('[answer needed] shell@Work');
  await expect(retained.locator('.program-status')).toHaveCount(0);
  expect(errors).toEqual([]);
  console.log('PASS: OSC 7501 tab titles and pinned cards, progress and blocked states, prompts/reset, keyboard acknowledgement, real PTY exit, and replay without query replies; no tty status footer');
} finally { await browser.close(); }
