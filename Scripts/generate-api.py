#!/usr/bin/env python3
"""Check the explicit OpenAPI contract against HTTP routes and embed it in the server."""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
METHODS = {'get', 'post', 'put', 'patch', 'delete', 'head', 'options'}


def routes(source):
    found = re.findall(r'router\.(get|post|put|patch|delete|head|options)\("([^"\n]+)"', source)
    found = [(method, path) for method, path in found if path == '/health' or path.startswith('/api/')]
    if len(found) != len(set(found)):
        raise ValueError('Duplicate HTTP routes')
    return set(found)


def validate(document, registered):
    documented = {(method, path) for path, operations in document['paths'].items() for method in operations if method in METHODS}
    if registered != documented:
        raise ValueError(f'API route coverage differs: undocumented={sorted(registered - documented)}, unregistered={sorted(documented - registered)}')
    identifiers = []
    for method, path in sorted(documented):
        operation = document['paths'][path][method]
        identifiers.append(operation['operationId'])
        if not operation.get('responses'):
            raise ValueError(f'Missing responses: {method} {path}')
        expected = set(re.findall(r'\{(\w+)\}', path))
        supplied = {item['name'] for item in operation.get('parameters', []) if item.get('in') == 'path' and item.get('required') is True}
        if expected != supplied:
            raise ValueError(f'Path parameters differ: {method} {path}')
    if len(identifiers) != len(set(identifiers)):
        raise ValueError('Duplicate operationId')

    def visit(value):
        if isinstance(value, dict):
            if '$ref' in value:
                reference = value['$ref']
                if not reference.startswith('#/'):
                    raise ValueError(f'Only local schema references are supported: {reference}')
                target = document
                try:
                    for key in reference[2:].split('/'):
                        target = target[key.replace('~1', '/').replace('~0', '~')]
                except (KeyError, TypeError):
                    raise ValueError(f'Unknown reference: {reference}') from None
            for item in value.values():
                visit(item)
        elif isinstance(value, list):
            for item in value:
                visit(item)
    visit(document)


def render(document):
    document = dict(document, paths={path: dict(sorted(operations.items())) for path, operations in sorted(document['paths'].items())})
    encoded = json.dumps(document, indent=2)
    # Swift raw literals must not be terminable by document contents.
    if '"""#' in encoded:
        raise ValueError('Unsupported Swift literal delimiter in OpenAPI document')
    return '// Generated by Scripts/generate-api.py from Docs/openapi.json. Do not edit.\nimport Foundation\nenum APIDocument {\n    static let data = Data(#"""\n' + encoded + '\n"""#.utf8)\n}\n'


def main():
    document = json.loads((ROOT/'Docs/openapi.json').read_text())
    source = '\n'.join(p.read_text() for p in sorted((ROOT/'Sources/Server').glob('*.swift')) if p.name != 'APIDocument.swift')
    validate(document, routes(source))
    output = render(document)
    target = ROOT/'Sources/Server/APIDocument.swift'
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != output:
            sys.exit('API docs are stale; run python3 Scripts/generate-api.py')
    else:
        target.write_text(output)


if __name__ == '__main__':
    main()
